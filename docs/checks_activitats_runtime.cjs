'use strict';
/* Contracte activitats.js + Cartes (PR B). Requereix el mateix vm que checks_fase2. */
module.exports=function activitatsRuntimeTests(ctx){
  const fs=require('fs'),assert=require('assert');
  const run=s=>require('vm').runInContext(s,ctx);
  const store=ctx.localStorageStore||(ctx.localStorage._store||(ctx.localStorage._store=new Map()));
  if(!ctx.localStorageStore)ctx.localStorageStore=store;
  const KEY='nostre-activitats-sessions-v1';
  const sessions=()=>{try{return JSON.parse(store.get(KEY)||'{}')}catch{return {}}};
  const personatgesJSON=JSON.parse(fs.readFileSync('data/personatges.json','utf8'));
  function completePairs(){const pairs=run('f2.match');for(const animal of new Set(pairs)){const inds=pairs.map((v,i)=>v===animal?i:null).filter(x=>x!==null);run(`clickCard(${inds[0]})`);run(`clickCard(${inds[1]})`);}}
  store.delete(KEY);
  run('activitatsResetMem()');
  run(`jocs.personatges=${JSON.stringify(personatgesJSON)}`);
  run('activitatsReg.failed=true;activitatsReg.ready=false');
  run('setupPairs()');
  completePairs();
  assert.equal(run('state.unlocked.pairs'),true,'fallback sense activitats.json');
  store.delete(KEY);
  run('setupPairs()');
  run(`go('pairs');setupPairs()`);
  const s1=run('f2.sessionId');
  run('setupPairs()');
  const s2=run('f2.sessionId');
  assert.notEqual(s1,s2,'setupPairs ha de generar sessionId nou');
  run('setupPairs()');
  completePairs();
  assert.equal(run('state.unlocked.pairs'),true,'completar sense tornar a la torre');
  const sid=run('f2.sessionId');
  assert.equal(run(`activitatCompleta('cartes',{sessionId:'${sid}',nivell:'exploradora'})`),false,'doble finalització mateixa sessió');
  const n1=(sessions().cartes?.completedSessionIds||[]).length;
  run(`action('end-pairs')`);
  assert.equal((sessions().cartes?.completedSessionIds||[]).length,n1,'end-pairs no afegeix sessió');
  run('setupPairs()');
  completePairs();
  assert.equal((sessions().cartes?.completedSessionIds||[]).length,n1+1,'segona partida');
  run('f2.cartesAventura.levelUnlocked=1;f2.cartesAventura.levelsCompleted.push(0)');
  run('setupPairs()');
  const antes=run('f2.sessionId');
  run(`action('pairs-level-1')`);
  assert.notEqual(run('f2.sessionId'),antes,'canvi de nivell = nova sessió');
  run('setupPairs()');
  run('clickCard(0)');
  assert.equal(sessions().cartes?.completedSessionIds?.length||0,n1+1,'abandonament sense nova finalització');
  store.set(KEY,'{corrupt');
  run('setupPairs()');
  completePairs();
  assert.equal(run('state.unlocked.pairs'),true,'localStorage sessions corrupte');
  run('f2.pairsLevel=0;setupPairs()');
  assert.equal(run('pairsNivellActual()'),'exploradora');
  run('f2.pairsLevel=1;setupPairs()');
  assert.equal(run('pairsNivellActual()'),'aventurera');
  const bloquejat=ctx.localStorage.setItem;
  ctx.localStorage.setItem=(k,v)=>{if(k===KEY)throw new Error('full');bloquejat(k,v);};
  run('setupPairs()');
  completePairs();
  assert.equal(run('state.unlocked.pairs'),true,'localStorage ple en sessions');
  console.log('OK: activitats runtime — contracte Cartes.');
};