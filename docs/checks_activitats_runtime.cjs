'use strict';
/* Contracte activitats.js + Cartes (PR B). Requereix el mateix vm que checks_fase2. */
module.exports=function activitatsRuntimeTests(ctx){
  const fs=require('fs'),assert=require('assert');
  const run=s=>require('vm').runInContext(s,ctx);
  const store=ctx.localStorageStore||(ctx.localStorage._store||(ctx.localStorage._store=new Map()));
  if(!ctx.localStorageStore)ctx.localStorageStore=store;
  const KEY='nostre-activitats-sessions-v1';
  const sessions=()=>{try{return JSON.parse(store.get(KEY)||'{}')}catch{return {}}};
  const personatgesJSON=JSON.parse(fs.readFileSync('data/personatges.json','utf8'));
  function completePairs(){const pairs=run('f2.match');for(const animal of new Set(pairs)){const inds=pairs.map((v,i)=>v===animal?i:null).filter(x=>x!==null);run(`clickCard(${inds[0]})`);run(`clickCard(${inds[1]})`);}}
  store.delete(KEY);
  run('activitatsResetMem()');
  run(`jocs.personatges=${JSON.stringify(personatgesJSON)}`);
  run('activitatsReg.failed=true;activitatsReg.ready=false');
  run('setupPairs()');
  completePairs();
  assert.equal(run('state.unlocked.pairs'),true,'fallback sense activitats.json');
  store.delete(KEY);
  run('setupPairs()');
  run(`go('pairs');setupPairs()`);
  const s1=run('f2.sessionId');
  run('setupPairs()');
  const s2=run('f2.sessionId');
  assert.notEqual(s1,s2,'setupPairs ha de generar sessionId nou');
  run('setupPairs()');
  completePairs();
  assert.equal(run('state.unlocked.pairs'),true,'completar sense tornar a la torre');
  const sid=run('f2.sessionId');
  assert.equal(run(`activitatCompleta('cartes',{sessionId:'${sid}',nivell:'exploradora'})`),false,'doble finalització mateixa sessió');
  const n1=(sessions().cartes?.completedSessionIds||[]).length;
  run(`action('end-pairs')`);
  assert.equal((sessions().cartes?.completedSessionIds||[]).length,n1,'end-pairs no afegeix sessió');
  run('setupPairs()');
  completePairs();
  assert.equal((sessions().cartes?.completedSessionIds||[]).length,n1+1,'segona partida');
  run('f2.cartesAventura.levelUnlocked=1;f2.cartesAventura.levelsCompleted.push(0)');
  run('setupPairs()');
  const antes=run('f2.sessionId');
  run(`action('pairs-level-1')`);
  assert.notEqual(run('f2.sessionId'),antes,'canvi de nivell = nova sessió');
  run('setupPairs()');
  run('clickCard(0)');
  assert.equal(sessions().cartes?.completedSessionIds?.length||0,n1+1,'abandonament sense nova finalització');
  store.set(KEY,'{corrupt');
  run('setupPairs()');
  completePairs();
  assert.equal(run('state.unlocked.pairs'),true,'localStorage sessions corrupte');
  run('f2.pairsLevel=0;setupPairs()');
  assert.equal(run('pairsNivellActual()'),'exploradora');
  run('f2.pairsLevel=1;setupPairs()');
  assert.equal(run('pairsNivellActual()'),'aventurera');
  const bloquejat=ctx.localStorage.setItem;
  ctx.localStorage.setItem=(k,v)=>{if(k===KEY)throw new Error('full');bloquejat(k,v);};
  run('setupPairs()');
  completePairs();
  assert.equal(run('state.unlocked.pairs'),true,'localStorage ple en sessions');
  ctx.localStorage.setItem=bloquejat;

  const ombresJSON=JSON.parse(fs.readFileSync('data/ombres-trapelles.json','utf8'));
  run(`jocs.ombres.data=${JSON.stringify(ombresJSON)}`);
  run(`activitatsReg.data=${JSON.stringify(JSON.parse(fs.readFileSync('data/activitats.json','utf8')))};activitatsReg.ready=true;activitatsReg.failed=false`);
  function ombresFind(){const tid=run('jocs.ombres.targetId'),ts=run('jocs.ombres.activeSecrets').find(s=>s.id===tid);run(`jocs.ombres.lx=${ts.x};jocs.ombres.ly=${ts.y};ombresTryFind(true)`);run('render()')}
  function ombresTreCerques(){for(let i=0;i<3;i++){ombresFind();assert.equal(run('jocs.ombres.stars'),i+1);if(i<2){run('ombresClearAuto();action("ombres-next-mission");render()');run(`action('ombres-begin-search');render()`)}}
    assert.equal(run('jocs.ombres.stars'),3);
    assert(run('jocs.ombres.levelVictoryRecorded'),'registre al 3r encert');
  }
  const o0=(sessions().ombres?.completedSessionIds||[]).length;
  run('resetOmbres();go("jocsOmbres");render()');
  run(`action('ombres-play-level-0');render()`);
  run(`action('ombres-begin-search');render()`);
  const sid0=run('jocs.ombres.sessionId');
  assert.ok(sid0,'sessionId nivell');
  run('ombresStartLevel(0);render()');
  assert.notEqual(run('jocs.ombres.sessionId'),sid0,'nova partida de nivell nou sessionId');
  run('ombresStartLevel(1);render()');
  assert.notEqual(run('jocs.ombres.sessionId'),sid0,'canvi de nivell nou sessionId');
  run('resetOmbres();ombresStartLevel(0);render()');
  const sid1=run('jocs.ombres.sessionId');
  run(`action('ombres-begin-search');render()`);
  ombresTreCerques();
  assert.equal((sessions().ombres?.completedSessionIds||[]).length,o0+1,'nivell 1 registrat');
  assert.equal(run(`activitatCompleta('ombres',{sessionId:'${sid1}',nivell:0})`),false,'dedupe mateixa sessió');
  assert.equal(run('state.unlocked["jocs-ombres"]'),undefined,'nivell 1 sense recompensa torre');
  assert.equal(run('f2.ombresSession.levelUnlocked'),1,'desbloqueig al 3r encert (abans CONTINUA)');
  assert(run('f2.ombresSession.levelsCompleted.includes(0)'),'nivell 0 marcat complet al 3r encert');
  run('ombresClearAuto();action("ombres-finish-level");render()');
  assert(run('jocs.ombres.phase')==='levelDone','celebració separada del registre');
  assert.equal(run('f2.ombresSession.levelUnlocked'),1,'desbloqueig inalterat després CONTINUA');
  run('resetOmbres();ombresStartLevel(0);render()');
  run(`action('ombres-begin-search');render()`);
  ombresFind();
  run(`action('end-jocs-ombres');nav('tower')`);
  assert.equal((sessions().ombres?.completedSessionIds||[]).length,o0+1,'abandonament sense victòria');
  run('resetOmbres();ombresStartLevel(0);render()');
  run(`action('ombres-begin-search');render()`);
  const sidExit=run('jocs.ombres.sessionId');
  ombresTreCerques();
  assert.equal((sessions().ombres?.completedSessionIds||[]).length,o0+2,'sortida després 3r encert conserva');
  assert.equal(run('f2.ombresSession.levelUnlocked'),1,'sortida immediata: desbloqueig guardat');
  run(`action('end-jocs-ombres');nav('tower')`);
  run('resetOmbres();go("jocsOmbres");render()');
  assert.equal(run('f2.ombresSession.levelUnlocked'),1,'reobrir: nivell 2 disponible sense CONTINUA');
  assert.equal((sessions().ombres?.completedSessionIds||[]).length,o0+2,'end-jocs sense duplicar');
  const sidReplay=run('jocs.ombres.sessionId');
  run('resetOmbres();ombresStartLevel(0);render()');
  assert.notEqual(run('jocs.ombres.sessionId'),sidReplay,'replay nou sessionId');
  run('activitatsReg.failed=true;activitatsReg.ready=false;activitatsReg.data=null');
  assert.equal(run(`activitatsLegacyKey('ombres')`),'jocs-ombres','fallback legacy sense activitats.json');
  run('resetOmbres();ombresStartLevel(3);render()');
  run(`action('ombres-begin-search');render()`);
  ombresTreCerques();
  assert.equal(run('state.unlocked["jocs-ombres"]'),true,'recompensa permanent nivell 4 sense JSON');
  run(`activitatsReg.data=${JSON.stringify(JSON.parse(fs.readFileSync('data/activitats.json','utf8')))};activitatsReg.ready=true;activitatsReg.failed=false`);
  run('resetOmbres();ombresStartLevel(3);render()');
  run(`action('ombres-begin-search');render()`);
  ombresTreCerques();
  run('action("ombres-nova-aventura");render()');
  assert.equal(run('state.unlocked["jocs-ombres"]'),true,'NOVA AVENTURA no esborra recompensa');

  const difJSON=JSON.parse(fs.readFileSync('data/diferencies.json','utf8'));
  run(`jocs.diferencies.data=${JSON.stringify(difJSON)}`);
  run(`activitatsReg.data=${JSON.stringify(JSON.parse(fs.readFileSync('data/activitats.json','utf8')))};activitatsReg.ready=true;activitatsReg.failed=false`);
  function difWinRound(){run(`(()=>{while(jocs.diferencies.phase==='searching'){const left=jocs.diferencies.active.filter(x=>!jocs.diferencies.found.has(x.id));if(!left.length)break;left.forEach(d=>jocs.diferencies.found.add(d.id));const goal=jocs.diferencies.active.length;if(jocs.diferencies.found.size>=goal){const goalR=difRoundsGoalEffective();jocs.diferencies.stars=Math.min(goalR,jocs.diferencies.stars+1);jocs.diferencies.phase='found';const ctx=jocs.diferencies.context||difContextLliure();if(ctx.mode==='missio')difRegisterMissionVictory();else if(jocs.diferencies.stars>=difRoundsGoal())difRegisterSessionVictory();difClearAuto();break}}})()`);}
  function difNextRonda(){run('difAdvanceRound();render()');}
  const d0=(sessions().diferencies?.completedSessionIds||[]).length;
  run('activitatsResetMem()');
  run('difPrepareFreeSession();resetDiferencies();go("jocsDiferencies")');
  const sidD=run('jocs.diferencies.sessionId');
  assert.ok(sidD,'diferencies sessionId');
  difWinRound();
  assert.equal((sessions().diferencies?.completedSessionIds||[]).length,d0,'1 ronda no registra sessio');
  assert.equal(run('state.unlocked["jocs-diferencies"]'),undefined,'1 ronda sense torre');
  difNextRonda();difWinRound();
  assert.equal((sessions().diferencies?.completedSessionIds||[]).length,d0,'2 rondes no registra sessio');
  difNextRonda();difWinRound();
  assert.equal((sessions().diferencies?.completedSessionIds||[]).length,d0+1,'sessio completa al 3r encert');
  assert.equal(run('state.unlocked["jocs-diferencies"]'),true,'recompensa tres rondes');
  assert.equal(run(`activitatCompleta('diferencies',{sessionId:'${sidD}',ambit:'sessio'})`),false,'dedupe sessio');
  run('action("end-jocs-diferencies");nav("tower")');
  assert.equal((sessions().diferencies?.completedSessionIds||[]).length,d0+1,'end-jocs sense duplicar');
  run('difPrepareFreeSession();resetDiferencies()');
  difWinRound();
  run('action("end-jocs-diferencies")');
  assert.equal((sessions().diferencies?.completedSessionIds||[]).length,d0+1,'abandonament sense victoria');
  const sidR=run('jocs.diferencies.sessionId');
  run('difPrepareFreeSession();resetDiferencies()');
  assert.notEqual(run('jocs.diferencies.sessionId'),sidR,'replay nou sessionId');
  run(`difDiferenciesStartMission({sceneId:'biblioteca',roundsGoal:1});resetDiferencies();go('jocsDiferencies')`);
  const sidM=run('jocs.diferencies.sessionId');
  assert.equal(run('jocs.diferencies.sceneId'),'biblioteca','missio fons fix');
  difWinRound();
  assert.equal((sessions().diferencies?.completedSessionIds||[]).length,d0+2,'missio registra ronda');
  assert.equal(run('state.unlocked["jocs-diferencies"]'),true,'missio no afegeix torre extra');
  run('difPrepareFreeSession();resetDiferencies()');
  difWinRound();difNextRonda();difWinRound();difNextRonda();difWinRound();
  assert.equal((sessions().diferencies?.completedSessionIds||[]).length,d0+3,'lliure després missio independent');

  console.log('OK: activitats runtime — Cartes + Ombres + Diferències.');
};