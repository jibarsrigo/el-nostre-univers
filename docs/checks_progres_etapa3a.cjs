'use strict';
const fs=require('fs'),vm=require('vm'),assert=require('node:assert/strict'),path=require('path');
const root=path.resolve(__dirname,'..');
const mem={};
const body={append(){},classList:{toggle(){}}};
const ctx=vm.createContext({document:{getElementById:()=>({innerHTML:''}),body,addEventListener(){}},localStorage:{getItem:k=>mem[k]??null,setItem:(k,v)=>{mem[k]=v}},sessionStorage:{getItem:()=>null,setItem(){}},window:{},setTimeout(){},console,Math,Date,fetch:()=>Promise.resolve({json:()=>Promise.resolve({})})});
const run=s=>vm.runInContext(s,ctx);
mem['nostre-fase1-records']=JSON.stringify({pairs:true,book:true});
mem['nostre-creacions-v3']=JSON.stringify([{kind:'creature',id:'c1',name:'Prova'}]);
vm.runInContext(fs.readFileSync(path.join(root,'js/progres.js'),'utf8'),ctx,{filename:'progres.js'});
const personatges=JSON.parse(fs.readFileSync(path.join(root,'data/personatges.json'),'utf8')).personatges;
ctx.personatgesList=personatges;
assert.equal(run('progresGrupsDescoberts().length'),0,'inici sense retroactiva');
assert(run('progresRegistraDescobert("pipa","cartes")'));
assert(run('progresRegistraDescobert("pipa","cartes")'));
assert.equal(run('progresGrupsDescoberts().length'),1,'dedupe grup');
assert.equal(run('progresGrupsDescoberts()[0]'),'pipa');
assert(run('progresRegistraDescobert("gat","ombres")'));
const snap=JSON.parse(mem['nostre-univers-progres-v1']);
assert.equal(snap.v,1);
assert.deepEqual(snap.permanent.amics,['gat','pipa']);
assert.ok(snap.permanent.fonts.pipa.includes('cartes'));
assert.ok(snap.permanent.fonts.gat.includes('ombres'));
const recordsAbans=mem['nostre-fase1-records'];
const creacionsAbans=mem['nostre-creacions-v3'];
const jugables=run('progresGrupsJugables(personatgesList).length');
assert.equal(run('progresQuedenPerDescobrir(personatgesList)'),jugables-2);
run('progresRegistraDescobert("bruna","cartes")');
assert.equal(mem['nostre-fase1-records'],recordsAbans,'records legacy intactes');
assert.equal(mem['nostre-creacions-v3'],creacionsAbans,'creacions intactes');
mem['nostre-univers-progres-v1']='{bad json';
assert.equal(run('progresGrupsDescoberts().length'),0,'JSON corrupte → buit');
mem['nostre-univers-progres-v1']=JSON.stringify({v:2,permanent:{amics:['x']}});
assert.equal(run('progresGrupsDescoberts().length'),0,'versió desconeguda → buit');
